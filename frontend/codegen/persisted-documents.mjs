// graphql-codegen plugin that writes the persisted document IDs the SPA uses
// to send cacheable queries as GET requests.
//
// Signed-out visitors send these operations as
// `GET /graphql?operationName=...&documentId=sha256:...` instead of POSTing
// the document, so Cloudflare can cache the responses (see
// `GraphqlController#persisted_query` on the Rails side). An ID is the
// SHA-256 of the operation's document exactly as it appears in
// `config/graphql/operations.json`, which is how `OperationAllowlist` finds
// it. Because the ID changes whenever the document does, a cached response
// for an old version of a query is never served for a new one.
//
// Only the operations listed in the `operations` config option get an ID.
// They should match `PublicResponseCache::OPERATIONS`, the operations whose
// signed-out responses the API lets Cloudflare cache, and
// spec/requests/graphql/persisted_get_spec.rb checks that they do.
import { createHash } from "node:crypto";
import { OperationTypeNode } from "graphql";
import { collectOperations } from "./operation-manifest.mjs";

export const plugin = (_schema, documents, config) => {
  const wanted = new Set(config.operations ?? []);
  const operations = collectOperations(documents);

  const ids = {};
  for (const name of [...wanted].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) {
    const entry = operations.get(name);
    if (!entry) {
      throw new Error(`Unknown operation "${name}" in the persisted documents config.`);
    }
    if (entry.operation.operation !== OperationTypeNode.QUERY) {
      throw new Error(`"${name}" isn't a query; only queries can be sent as GET requests.`);
    }
    ids[name] = `sha256:${createHash("sha256").update(entry.document).digest("hex")}`;
  }

  return [
    "// Generated by `pnpm run codegen` (codegen/persisted-documents.mjs). Do not edit.",
    "",
    "/** Persisted document IDs for the queries signed-out visitors send as GET requests. */",
    `export const persistedDocumentIds: Readonly<Record<string, string>> = ${JSON.stringify(ids, null, 2)};`,
    ""
  ].join("\n");
};
